def _build_capability_section() -> str:
    """根据已注册工具生成【二、能力】段。

    规则：
    1. 绑定工具未注册 → 跳过该能力行（可插拔核心）
    2. 多工具共享同一能力描述（如 save_memory/query_memory）→ 去重只输出一行
    3. None（MCP 兜底）→ 恒输出
    """
    seen: set[str] = set()
    lines: list[str] = []
    for bound_tool, description in _CAPABILITY_REGISTRY:
        if bound_tool is not None and bound_tool not in _REGISTERED_TOOL_NAMES:
            continue
        if description in seen:
            continue
        seen.add(description)
        lines.append(f"- {description}")
    return "\n".join(lines)


